// zero-docs v2.0.0 — Living Documentation Engine
// INT-145 — Keeps README and welcome message in sync with live state
//
// BOUNDARY RULE: README lines 1-37 (the DYNAMIC section) are hand-maintained --
//                zero-docs owns README lines 38+ (static section)
//                zero-release wrote them until INT-247 retired it; zero-docs never does.
//
// Commands:
//   sync             update the README numbers, the tools index and the public docs
//   check            what is out of date (dry run); exits 1 when the tools index is stale
//   status           what docs exist, last updated
//   links            every README link resolves
//   public           generate the curated public docs set
//   readme-preview   one tool's scaffold README (writes nothing)
//   readme-index     write the tools index
//   readme-generate  scaffold missing tool READMEs; never touches one a person owns

mod toolgen;
use colored::*;

const BOUNDARY_MARKER: &str = "<!-- END DYNAMIC SECTION -->";

/// The root README footer. Constant on purpose: a version or a date written here is a second copy
/// of a fact someone else owns (Cargo.toml owns the version, git owns the date), and it was wrong
/// the moment it was written (INT-291, G3b).
const FOOTER: &str =
    "*Auto-generated by zero-docs -- the live numbers above are refreshed by `zero-docs sync`.*";
// INT-265: read from Cargo, so --version cannot drift from the package as zero-git did.
const VERSION: &str = env!("CARGO_PKG_VERSION");

/// INT-315 Phase 3: generate public docs set -- curated, no internal content
fn cmd_public(dry_run: bool) {
    use std::fs;
    let root = zero_core::paths::core_dir();
    let docs_dir = root.join("docs");
    let public_dir = docs_dir.join("public");

    // Public docs -- curated set, no internal language
    let public_files = [
        ("COMMAND-GUIDE.md", "Command Reference"),
        ("ARCHITECTURE.md", "Architecture"),
        ("PHILOSOPHY.md", "Philosophy"),
        ("NSH-PHILOSOPHY.md", "Shell Philosophy"),
        ("NOVASHELL.md", "Shell Reference"),
    ];

    if dry_run {
        println!("  -> public/ would contain {} docs:", public_files.len());
        for (file, title) in &public_files {
            let src = docs_dir.join(file);
            let exists = if src.exists() { "✅" } else { "❌ missing" };
            println!("     {} {} ({})", exists, title, file);
        }
        return;
    }

    if !public_dir.exists() {
        if let Err(e) = fs::create_dir_all(&public_dir) {
            eprintln!("  ❌ Could not create docs/public/: {}", e);
            return;
        }
    }

    // Generate index.md
    let version = std::fs::read_to_string(zero_core::paths::version_file())
        .unwrap_or_default()
        .trim()
        .to_string();
    let mut index = format!(
        "# Project 0 Documentation\n\n> {}\n\n## Contents\n\n",
        version
    );

    let mut copied = 0usize;
    for (file, title) in &public_files {
        let src = docs_dir.join(file);
        let dst = public_dir.join(file);
        if src.exists() {
            if let Ok(src_content) = fs::read_to_string(&src) {
                // Strip any lines containing internal markers
                let clean: String = src_content
                    .lines()
                    .filter(|l| !l.contains("INT-") || l.contains("INT-") && l.starts_with('#'))
                    .collect::<Vec<_>>()
                    .join("\n");
                let _ = fs::write(&dst, clean);
                index.push_str(&format!("- [{}]({})\n", title, file));
                copied += 1;
            }
        }
    }

    let _ = fs::write(public_dir.join("index.md"), index);
    println!(
        "  {} docs/public/ -- {} docs generated",
        "✅".normal(),
        copied
    );
}

fn main() {
    // INT-256: FIRST statement, before any output. `tool | head -3` must not print a panic.
    zero_core::restore_sigpipe();
    let args: Vec<String> = std::env::args().collect();
    let cmd = args.get(1).map(|s| s.as_str()).unwrap_or("help");

    match cmd {
        // INT-265: --version prints the version. It fell through to the banner.
        "--version" | "-V" => println!("zero-docs {}", VERSION),
        "--health" | "health" => {
            println!("zero-docs v{} — healthy", VERSION);
        }
        "sync" => {
            cmd_readme(false);
            toolgen::cmd_index(false);
            verify_links(false);
            cmd_public(false);
            println!("  {} All docs synced", "✅".normal());
        }
        "public" => {
            let dry = args.get(2).map(|s| s == "--dry-run").unwrap_or(false);
            cmd_public(dry);
        }
        "check" => {
            cmd_readme(true);
            verify_links(true);
            match toolgen::check_index() {
                Ok(stale) if stale.is_empty() => {
                    println!("  \u{2705} tools/README.md matches every Cargo.toml")
                }
                Ok(stale) => {
                    eprintln!(
                        "  \u{2717} tools/README.md is stale for: {} -- run `zero-docs sync`",
                        stale.join(", ")
                    );
                    std::process::exit(1);
                }
                Err(e) => {
                    eprintln!("  \u{2717} {}", e);
                    std::process::exit(1);
                }
            }
        }
        "verify-links" | "links" => {
            verify_links(false);
        }
        "status" => cmd_status(),
        "readme-preview" => {
            let name = args.get(2).map(|s| s.as_str()).unwrap_or("");
            toolgen::cmd_preview_one(name);
        }
        "readme-index" => {
            let dry = args.get(2).map(|s| s == "--dry-run").unwrap_or(false);
            toolgen::cmd_index(dry);
        }
        "readme-generate" => {
            let dry = args.get(2).map(|s| s == "--dry-run").unwrap_or(false);
            toolgen::cmd_generate(dry);
        }
        _ => cmd_help(),
    }
}

struct LiveState {
    version: String,
    theme: String,
    tool_count: usize,
    intent_complete: usize,
    intent_planned: usize,
    commits: String,
    health: String,
    core_domains: usize,
}

fn gather_state() -> LiveState {
    let root = zero_core::paths::core_dir();

    let version = std::fs::read_to_string(zero_core::paths::version_file())
        .unwrap_or_else(|_| "unknown".to_string())
        .trim()
        .to_string();

    let changelog =
        std::fs::read_to_string(root.join("zero/meta/CHANGELOG.md")).unwrap_or_default();
    let theme = changelog
        .lines()
        .find(|l| l.contains(&format!("[{}]", version)))
        .and_then(|l| l.split(" — ").nth(1))
        .and_then(|s| s.split('(').next())
        .map(|s| s.trim().to_string())
        .unwrap_or_else(|| "Built From Zero".to_string());

    // Count registered tools from tools.toml -- the same file the doctor path-resilience
    // check reads, which is the point of the comment that used to be here. They disagreed.
    //
    // ⚠️ THE PATH WAS WRONG AND THE FAILURE WAS SILENT. registry/tools.toml has not existed
    // since INT-061 moved directories into the platform directory; the file is at
    // zero/registry/tools.toml. read_to_string failed, unwrap_or(0) turned that into a
    // confident zero, and zero-docs sync WROTE 0 custom Rust tools into the front page of
    // the repository -- then printed a green check. Caught 2026-09-02 by reading tools: 0 in
    // its own success line while 26 tools were deployed.
    //
    // A missing registry is not zero tools. It is a fact the generator cannot establish, and
    // writing a number it did not measure is how the README came to state something false.
    let tool_count = match zero_core::registry::read() {
        // ⚠️ NOT retired ONES. Fixing the path exposed the predicate: counting every
        // name = line gave 51, and 13 of those entries are RETIRED -- core-diff,
        // the old notifier and the old terminal among them, two of those retired the same
        // day. The sentence in the README is about tools Project 0 HAS, so a tool it
        // deliberately removed does not count toward it.
        //
        // Rows, not lines: retired and type belong to the entry that names them, so a row is
        // judged whole. The core parses the registry (decision 149); this only decides which
        // rows count. 51 entries, 13 retired, 38 live.
        // ⭐ AND NOT type = "cargo" EITHER, MEASURED 2026-09-15.
        //
        // This said 36 while the tree held 26 crates. The arithmetic was honest; the SET
        // was wrong. Eleven live entries name nothing in rust-tools/:
        //
        //   nine cargo-*   cargo-nextest, -watch, -udeps, -flamegraph, -cache,
        //                 -install-update, -set-version, -upgrade, -miri.
        //                 They are EXTERNAL cargo subcommands, not tools this
        //                 project wrote.
        //   core, nsh     REAL, and correctly `type = "rust"` -- they just live
        //                 elsewhere (zero/engine/, and novashell's binary).
        //
        // The registry ALREADY KNEW. Every cargo entry carries `type = "cargo"` and
        // `deployable = false`. This counter read neither field, so a sentence about
        // tools THIS PROJECT WROTE included nine it merely INSTALLS.
        //
        // 26 crates + the engine = 27, which is what this now returns.
        Ok(rows) => rows
            .iter()
            .filter(|r| !r.retired && r.kind.as_deref() != Some("cargo"))
            .count(),
        Err(e) => {
            eprintln!(
                "  {} -- refusing to write a tool count it did not measure",
                e
            );
            std::process::exit(1);
        }
    };

    // Count intents by scanning all categories — mirrors doctor check_intents logic
    let (intent_complete, intent_planned) = {
        let intent_dir = zero_core::paths::intents_dir();
        let categories = [
            "complete",
            "decisions",
            "experiments",
            "philosophy",
            "future",
            "cancelled",
            "deferred",
            "incidents",
            "active",
        ];
        let mut complete = 0usize;
        let mut planned = 0usize;
        for cat in &categories {
            if let Ok(entries) = std::fs::read_dir(intent_dir.join(cat)) {
                for entry in entries.flatten() {
                    if entry.path().extension().map(|e| e == "md").unwrap_or(false) {
                        if let Ok(text) = std::fs::read_to_string(entry.path()) {
                            if text.contains("status: complete") {
                                complete += 1;
                            } else if text.contains("status: planned") {
                                planned += 1;
                            }
                        }
                    }
                }
            }
        }
        (complete, planned)
    };

    // INT-250: git, not the old commit-count file. See the note in autobiography/mod.rs.
    let commits = std::process::Command::new("git")
        .args([
            "-C",
            &zero_core::paths::core_dir().to_string_lossy(),
            "rev-list",
            "--count",
            "HEAD",
        ])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "?".to_string());

    // Read live health — prefer ~/.cache/zero/health-status, fall back to state.db cache
    let health = {
        // INT-247 Layer 3a: the PATH only. The `.or_else` below is a SECOND source -- the
        // state.db cache -- which read_health() knows nothing about, so adopting it would
        // silently drop the fallback. Only the hand-built path changes here.
        std::fs::read_to_string(zero_core::paths::health_status_file())
            .or_else(|_| std::fs::read_to_string(zero_core::paths::cache_dir().join("health.txt")))
            // Neither source readable: "?", not "100". Unknown is not a perfect score -- the
            // INT-192 class, fixed on the way under INT-247.
            .unwrap_or_else(|_| "?".to_string())
            .trim()
            .trim_end_matches('%')
            .to_string()
    };

    // ⚠️ THE SAME BUG AS THE TOOL COUNT, IN THE SAME FILE, FROM THE SAME CAUSE. The path
    // was engine/src/domains and the engine has been at zero/engine since INT-061
    // moved directories. read_dir failed, unwrap_or(0) made it zero, and the README
    // advertised 0+ native domains while 55 directories sat on disk. 57 is what ls counts,
    // because ls counts mod.rs too -- the number in the README is directories.
    //
    // TWO sites computed a path into a directory INT-061 moved. The other six root.join
    // calls in this file are correct -- docs, README.md and link resolution really are
    // relative to the repo root. Counted after writing three from memory and being wrong.
    let domains_path = zero_core::paths::core_dir().join("zero/engine/src/domains");
    let core_domains = match std::fs::read_dir(&domains_path) {
        Ok(d) => d.flatten().filter(|e| e.path().is_dir()).count(),
        Err(e) => {
            eprintln!(
                "  cannot read {} ({}) -- refusing to write a domain count it did not measure",
                domains_path.display(),
                e
            );
            std::process::exit(1);
        }
    };

    LiveState {
        version,
        theme,
        tool_count,
        intent_complete,
        intent_planned,
        commits,
        health,
        core_domains,
    }
}

fn cmd_readme(dry_run: bool) {
    let root = zero_core::paths::core_dir();
    let readme_path = root.join("README.md");

    let content = match std::fs::read_to_string(&readme_path) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("  {} Cannot read README: {}", "✗".bright_red(), e);
            return;
        }
    };

    // Find boundary — NEVER touch above it
    let boundary_pos = match content.find(BOUNDARY_MARKER) {
        Some(p) => p + BOUNDARY_MARKER.len(),
        None => {
            eprintln!(
                "  {} Boundary marker not found in README — aborting",
                "✗".bright_red()
            );
            return;
        }
    };

    let state = gather_state();

    // ── Targeted patch strategy ───────────────────────────────────────────────
    // Only patch specific live numbers — never replace prose or structure
    let header = content[..boundary_pos].to_string();
    let mut body = content[boundary_pos..].to_string();

    // 1. Tool count: "68 custom Rust tools"
    let tool_pattern = regex_replace_first(
        &body,
        r"\d+ custom Rust tools",
        &format!("{} custom Rust tools", state.tool_count),
    );
    body = tool_pattern;

    // 2. Domain count: "33+ native domains"
    let domain_pattern = regex_replace_first(
        &body,
        r"\d+\+ native domains",
        &format!("{}+ native domains", state.core_domains),
    );
    body = domain_pattern;

    // 3. Intent count: "104 complete intents"
    let intent_pattern = regex_replace_first(
        &body,
        r"\d+ complete intents",
        &format!("{} complete intents", state.intent_complete),
    );
    body = intent_pattern;

    // 4. Footer: constant text, no date and no version. Cargo.toml owns the version and git
    // owns the date; a stamp rewritten on every run is never true for long and dirties the
    // tree on every sync (INT-291, G3b).
    let footer = FOOTER;
    body = if let Some(start) = body.find("*Auto-generated by zero-docs") {
        let end = body[start..]
            .find('\n')
            .map(|i| start + i)
            .unwrap_or(body.len());
        format!("{}{}{}", &body[..start], footer, &body[end..])
    } else {
        format!("{}\n{}\n", body.trim_end(), footer)
    };

    let new_content = format!("{}{}", header, body);

    // Data-only diff (ignore timestamp line) — drives check/status
    let data_changed = strip_timestamp(&body) != strip_timestamp(&content[boundary_pos..]);

    // Full diff including timestamp — drives actual write
    if content == new_content {
        println!("  {} README already up to date", "✅".normal());
        return;
    }

    if dry_run {
        if data_changed {
            println!("  {} README would update:", "→".bright_cyan());
            println!(
                "     tools: {}  domains: {}+  intents: {}  version: {}",
                state.tool_count.to_string().bright_white(),
                state.core_domains.to_string().bright_white(),
                state.intent_complete.to_string().bright_white(),
                state.version.bright_green(),
            );
        } else {
            println!("  {} README already up to date", "✅".normal());
        }
    } else {
        match std::fs::write(&readme_path, &new_content) {
            Ok(_) => println!(
                "  {} README updated — tools: {}  domains: {}+  intents: {}",
                "✅".normal(),
                state.tool_count.to_string().bright_white(),
                state.core_domains.to_string().bright_white(),
                state.intent_complete.to_string().bright_white(),
            ),
            Err(e) => eprintln!("  {} Cannot write README: {}", "✗".bright_red(), e),
        }
    }
}

// Strip auto-generated timestamp line for data-only comparisons
fn strip_timestamp(s: &str) -> String {
    s.lines()
        .filter(|l| !l.starts_with("*Auto-generated by zero-docs"))
        .collect::<Vec<_>>()
        .join("\n")
}

// Simple regex-free pattern replacer for "digits + suffix" patterns
/// Replace EVERY occurrence, which the name used to promise it would not.
///
/// ⚠️ IT REPLACED THE FIRST AND STOPPED, and README.md carries the phrase twice. The
/// static section said 38 custom Rust tools on line 54 and 0 custom Rust tools on line
/// 116 -- the same document, the same generator, the same sync run. Line 116 had never
/// been reached since the phrase was added below it.
///
/// Not a regex despite the name: a literal suffix search, walking back over the digits
/// in front of it. That is fine and stays. What changes is that it keeps going.
fn regex_replace_first(text: &str, pattern_kind: &str, replacement: &str) -> String {
    let suffix = match pattern_kind {
        r"\d+ custom Rust tools" => " custom Rust tools",
        r"\d+\+ native domains" => "+ native domains",
        r"\d+ complete intents" => " complete intents",
        _ => return text.to_string(),
    };
    let mut out = String::new();
    let mut rest = text;
    while let Some(suffix_pos) = rest.find(suffix) {
        let before = &rest[..suffix_pos];
        let digit_start = before
            .rfind(|c: char| !c.is_ascii_digit())
            .map(|i| i + 1)
            .unwrap_or(0);
        // No digits in front of the suffix: not a count, so leave it and move past.
        if digit_start == suffix_pos {
            let cut = suffix_pos + suffix.len();
            out.push_str(&rest[..cut]);
            rest = &rest[cut..];
            continue;
        }
        out.push_str(&rest[..digit_start]);
        out.push_str(replacement);
        rest = &rest[suffix_pos + suffix.len()..];
    }
    out.push_str(rest);
    out
}

fn verify_links(dry_run: bool) -> bool {
    let root = zero_core::paths::core_dir();
    let readme_path = root.join("README.md");
    let content = match std::fs::read_to_string(&readme_path) {
        Ok(c) => c,
        Err(_) => return true,
    };

    let mut broken: Vec<String> = vec![];

    // Scan for markdown links [text](path)
    let mut pos = 0;
    let bytes = content.as_bytes();
    while pos < content.len() {
        if let Some(start) = content[pos..].find("](") {
            let link_start = pos + start + 2;
            if let Some(end) = content[link_start..].find(')') {
                let link = &content[link_start..link_start + end];
                // Only check relative links (not http/https/mailto/#)
                if !link.starts_with("http")
                    && !link.starts_with('#')
                    && !link.starts_with("mailto")
                    && !link.is_empty()
                {
                    let full_path = root.join(link);
                    if !full_path.exists() {
                        broken.push(link.to_string());
                    }
                }
                pos = link_start + end + 1;
            } else {
                break;
            }
        } else {
            break;
        }
        let _ = bytes; // suppress warning
    }

    if broken.is_empty() {
        if !dry_run {
            println!(
                "  {} README links verified — all resolve correctly",
                "✅".normal()
            );
        }
        return true;
    }

    for link in &broken {
        println!(
            "  {} Broken link: {}",
            "✗".bright_red(),
            link.bright_white()
        );
    }
    if dry_run {
        println!(
            "  {} {} broken link(s) found — fix before release",
            "⚠️ ".normal(),
            broken.len()
        );
    }
    false
}

fn cmd_status() {
    let state = gather_state();
    let root = zero_core::paths::core_dir();

    println!();
    println!("  {} zero-docs status", "📋".normal());
    println!("{}", "  ─────────────────────────────────────".dimmed());
    println!(
        "  {}  v{} — {}",
        "Version:".dimmed(),
        state.version.bright_green(),
        state.theme.dimmed()
    );
    println!(
        "  {}    {}",
        "Tools:".dimmed(),
        state.tool_count.to_string().bright_white()
    );
    println!(
        "  {}  {} complete, {} planned",
        "Intents:".dimmed(),
        state.intent_complete.to_string().bright_white(),
        state.intent_planned.to_string().dimmed()
    );
    println!(
        "  {}  {}",
        "Commits:".dimmed(),
        state.commits.bright_white()
    );
    println!(
        "  {}   {}%",
        "Health:".dimmed(),
        state.health.bright_green()
    );
    println!(
        "  {} {}",
        "Core domains:".dimmed(),
        state.core_domains.to_string().bright_white()
    );
    println!();

    // Check README — use actual diff logic, not shallow version check
    let readme_ok = {
        let readme_path = root.join("README.md");
        if let Ok(content) = std::fs::read_to_string(&readme_path) {
            if let Some(boundary_pos) = content
                .find(BOUNDARY_MARKER)
                .map(|p| p + BOUNDARY_MARKER.len())
            {
                let mut body = content[boundary_pos..].to_string();
                body = regex_replace_first(
                    &body,
                    r"\d+ custom Rust tools",
                    &format!("{} custom Rust tools", state.tool_count),
                );
                body = regex_replace_first(
                    &body,
                    r"\d+\+ native domains",
                    &format!("{}+ native domains", state.core_domains),
                );
                body = regex_replace_first(
                    &body,
                    r"\d+ complete intents",
                    &format!("{} complete intents", state.intent_complete),
                );
                // Compare data only — ignore timestamp line
                let strip = |s: &str| {
                    s.lines()
                        .filter(|l| !l.starts_with("*Auto-generated by zero-docs"))
                        .collect::<Vec<_>>()
                        .join("\n")
                };
                strip(&content[boundary_pos..]) == strip(&body)
            } else {
                false
            }
        } else {
            false
        }
    };
    println!(
        "  {}      {}",
        "README:".dimmed(),
        if readme_ok {
            "✅ up to date".bright_green().to_string()
        } else {
            "⚠  numbers outdated — run: zero-docs readme"
                .yellow()
                .to_string()
        }
    );
    println!();
}

